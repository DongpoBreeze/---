const allowed = new Set(IOS_SOURCE_FILES);
const buildScripts = new Set(IOS_SOURCE_FILES.filter((file) => file.startsWith('scripts/')));
const pngSignature = Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]);
const privatePngChunks = new Set(['eXIf', 'tEXt', 'zTXt', 'iTXt']);

export function canonicalSourcePath(input) {
  if (typeof input !== 'string' || !input || /[\0\r\n:]/.test(input)) return null;
  const value = input.replaceAll('\\', '/');
  if (value.startsWith('/') || value.split('/').some((part) => !part || part === '.' || part === '..')) return null;
  return value;
}

export function isAllowedSourcePath(input) {
  const value = canonicalSourcePath(input);
  return value !== null && allowed.has(value);
}

export function expectedEasIgnore() {
  const parents = new Set();
  for (const file of IOS_SOURCE_FILES) {
    let parent = path.posix.dirname(file);
    while (parent !== '.') {
      parents.add(parent);
      parent = path.posix.dirname(parent);
    }
  }
  const directories = [...parents].sort((a, b) => a.split('/').length - b.split('/').length || a.localeCompare(b));
  return [
    '# Generated by: node scripts/ios-source-policy.mjs --write-easignore',
    '# Fail closed: only the reviewed client inputs below may enter an EAS archive.',
    '# No server data, validation photos, dotenv, backups, signing files, or local artifacts.',
    '/*',
    ...directories.flatMap((directory) => [`!/${directory}/`, `/${directory}/*`]),
    ...IOS_SOURCE_FILES.map((file) => `!/${file}`),
    '',
  ].join('\n');
}

// Read only approved system values. In particular, never read the value of any
// AI, EXPO_PUBLIC_*, npm token, NODE_OPTIONS, or developer credential variable.
export function iosBuildEnvironment(input = process.env) {
  const systemNames = new Set([
    'PATH', 'PATHEXT', 'SYSTEMROOT', 'WINDIR', 'COMSPEC', 'TEMP', 'TMP', 'TMPDIR',
    'USERPROFILE', 'HOME', 'HOMEDRIVE', 'HOMEPATH', 'APPDATA', 'LOCALAPPDATA',
    'LANG', 'LC_ALL', 'LC_CTYPE', 'NUMBER_OF_PROCESSORS', 'PROCESSOR_ARCHITECTURE',
    'SHELL', 'TERM', 'COLORTERM', 'DEVELOPER_DIR', 'SDKROOT', 'RUBY_ROOT', 'GEM_HOME', 'GEM_PATH',
  ]);
  const result = {};
  for (const name of Object.keys(input)) {
    if (systemNames.has(name.toUpperCase()) && typeof input[name] === 'string') result[name] = input[name];
  }
  return {
    ...result,
    CI: '1',
    NODE_ENV: 'production',
    EXPO_NO_DOTENV: '1',
    EXPO_NO_CLIENT_ENV_VARS: '1',
    EXPO_NO_TELEMETRY: '1',
    EXPO_OFFLINE: '1',
  };
}

export const sha256 = (bytes) => createHash('sha256').update(bytes).digest('hex');

export function inspectPng(bytes, file) {
  if (!bytes.subarray(0, 8).equals(pngSignature)) throw new Error(`Expected a PNG app asset: ${file}`);
  const chunks = [];
  const compressed = [];
  let offset = 8;
  while (offset + 12 <= bytes.length) {
    const size = bytes.readUInt32BE(offset);
    const type = bytes.toString('ascii', offset + 4, offset + 8);
    if (offset + size + 12 > bytes.length) throw new Error(`Truncated PNG asset: ${file}`);
    if (privatePngChunks.has(type)) throw new Error(`Unreviewed PNG metadata is not allowed: ${file}`);
    if (type === 'IDAT') compressed.push(bytes.subarray(offset + 8, offset + 8 + size));
    chunks.push(type);
    offset += size + 12;
    if (type === 'IEND') break;
  }
  if (offset !== bytes.length || chunks[0] !== 'IHDR' || chunks.at(-1) !== 'IEND') throw new Error(`Invalid PNG chunks: ${file}`);
  const result = { width: bytes.readUInt32BE(16), height: bytes.readUInt32BE(20), colorType: bytes[25], chunks };
  if (/^assets\/icon(?:-dark)?\.png$/.test(file) && (result.width !== 1024 || result.height !== 1024)) {
    throw new Error(`iOS app icon must be 1024 × 1024: ${file}`);
  }
  if (result.colorType === 2) result.opaque = true;
  else if (result.colorType === 6 && bytes[24] === 8 && bytes[28] === 0) {
    const raw = inflateSync(Buffer.concat(compressed), { maxOutputLength: (result.width * 4 + 1) * result.height });
    const stride = result.width * 4;
    if (raw.length !== (stride + 1) * result.height) throw new Error(`Invalid RGBA scanlines: ${file}`);
    let previous = Buffer.alloc(stride);
    let transparentPixels = 0;
    const paeth = (a, b, c) => {
      const p = a + b - c;
      const distances = [Math.abs(p - a), Math.abs(p - b), Math.abs(p - c)];
      return distances[0] <= distances[1] && distances[0] <= distances[2] ? a : distances[1] <= distances[2] ? b : c;
    };
    for (let y = 0; y < result.height; y += 1) {
      const filter = raw[y * (stride + 1)];
      if (filter > 4) throw new Error(`Invalid PNG scanline filter: ${file}`);
      const line = Buffer.from(raw.subarray(y * (stride + 1) + 1, (y + 1) * (stride + 1)));
      for (let x = 0; x < stride; x += 1) {
        const left = x >= 4 ? line[x - 4] : 0;
        const up = previous[x];
        const diagonal = x >= 4 ? previous[x - 4] : 0;
        const predictor = [0, left, up, Math.floor((left + up) / 2), paeth(left, up, diagonal)][filter];
        line[x] = (line[x] + predictor) & 255;
        if (x % 4 === 3 && line[x] !== 255) transparentPixels += 1;
      }
      previous = line;
    }
    result.opaque = transparentPixels === 0;
    result.transparentPixels = transparentPixels;
  }
  // Expo SDK 57 intentionally preserves transparency for iOS 18 dark icons;
  // the universal/light icon must be opaque.
  if (file === 'assets/icon.png' && result.opaque !== true) throw new Error(`The iOS universal/light app icon must be opaque: ${file}`);
  return result;
}

function assertClientText(file, text) {
  const checks = [
    [/-----BEGIN (?:[A-Z ]+ )?PRIVATE KEY-----/, 'private key material'],
    [/\bsk-(?:proj-)?[A-Za-z0-9_-]{20,}\b/, 'a credential-shaped literal'],
    [/(?:apiKey|api_key|access_token|refresh_token|password)\s*["']?\s*[:=]\s*["'][^"'\r\n]{8,}["']/i, 'an embedded credential'],
    [/\b(?:heightCm|weightKg)\s*:\s*\d+(?:\.\d+)?\b/, 'a prefilled body measurement'],
    [/data:(?:image|video)\/[\w.+-]+;base64,[A-Za-z0-9+/]{64,}/, 'embedded personal media'],
    [/(?:C:\\\\?Users\\|\/Users\/|\/home\/)[^\s"']+/i, 'a developer home path'],
  ];
  if (!buildScripts.has(file)) {
    checks.push([/\bprocess\s*(?:\.\s*env|\[\s*["']env["']\s*\])|\bimport\.meta\.env/, 'client build environment access']);
  }
  for (const [pattern, description] of checks) {
    if (pattern.test(text)) throw new Error(`Source policy rejected ${description} in ${file}. Matched values are never logged.`);
  }
}

export function assertIosConfiguration(app, eas, packageJson) {
  const expo = app.expo;
  if (!expo?.ios?.bundleIdentifier || !expo.ios.buildNumber) throw new Error('iOS bundleIdentifier and local buildNumber are required.');
  if (expo.extra) {
    const projectId = expo.extra.eas?.projectId;
    if (Object.keys(expo.extra).some((key) => key !== 'eas') || Object.keys(expo.extra.eas ?? {}).some((key) => key !== 'projectId') || !/^[0-9a-f]{8}(?:-[0-9a-f]{4}){3}-[0-9a-f]{12}$/i.test(projectId ?? '')) {
      throw new Error('Only a public EAS project ID may be added to app.json extra; private runtime settings are forbidden.');
    }
  }
  if (expo.ios.appleTeamId) throw new Error('Apple teams must be selected with the signing account rather than hardcoded into this source package.');
  const permissions = expo.ios.infoPlist ?? {};
  for (const key of ['NSCameraUsageDescription', 'NSPhotoLibraryUsageDescription']) {
    if (typeof permissions[key] !== 'string' || !permissions[key].trim()) throw new Error(`Missing iOS permission explanation: ${key}`);
  }
  for (const key of Object.keys(permissions)) {
    if (/Microphone|Health|Tracking|FaceID/i.test(key)) throw new Error(`The app does not use the iOS capability ${key}.`);
  }
  if (permissions.NSAppTransportSecurity?.NSAllowsArbitraryLoads !== false) throw new Error('iOS must keep arbitrary cleartext network loads disabled.');
  if (expo.ios.privacyManifests?.NSPrivacyTracking !== false) throw new Error('iOS tracking must stay disabled.');
  const pluginOptions = (name) => expo.plugins?.find((entry) => Array.isArray(entry) && entry[0] === name)?.[1];
  if (pluginOptions('expo-image-picker')?.microphonePermission !== false) throw new Error('Explicitly disable the unused image-picker microphone permission.');
  if (pluginOptions('expo-secure-store')?.faceIDPermission !== false) throw new Error('Explicitly disable the unused Face ID permission.');
  if (eas.cli?.appVersionSource !== 'local') throw new Error('Use the local, reviewable app and build versions.');
  for (const [name, distribution, simulator] of [
    ['ios-simulator', 'internal', true],
    ['ios-internal', 'internal', false],
    ['ios-testflight', 'store', false],
  ]) {
    const profile = eas.build?.[name];
    if (!profile || profile.distribution !== distribution || profile.ios?.simulator !== simulator || profile.ios?.buildConfiguration !== 'Release') {
      throw new Error(`Invalid EAS iOS build profile: ${name}`);
    }
    if (profile.env?.EXPO_NO_DOTENV !== '1' || profile.env?.EXPO_NO_CLIENT_ENV_VARS !== '1') {
      throw new Error(`EAS profile ${name} must disable dotenv loading and client environment injection.`);
    }
    if (Object.keys(profile.env).some((key) => key.startsWith('EXPO_PUBLIC_'))) throw new Error(`EAS profile ${name} contains a client environment value.`);
  }
  if (packageJson.scripts?.['eas-build-pre-install'] !== 'node scripts/ios-source-policy.mjs --check') {
    throw new Error('The EAS source-policy pre-install guard is missing.');
  }
}

async function approvedFile(root, file) {
  const relative = canonicalSourcePath(file);
  if (!relative || !allowed.has(relative)) throw new Error('An unapproved source path was requested.');
  let current = root;
  const parts = relative.split('/');
  for (let index = 0; index < parts.length; index += 1) {
    current = path.join(current, parts[index]);
    const stat = await fs.lstat(current);
    if (stat.isSymbolicLink()) throw new Error(`Source links are not allowed: ${relative}`);
    if (index < parts.length - 1 ? !stat.isDirectory() : !stat.isFile()) throw new Error(`Expected a regular source file: ${relative}`);
  }
  const actual = await fs.realpath(current);
  const difference = path.relative(root, actual);
  if (difference === '..' || difference.startsWith(`..${path.sep}`) || path.isAbsolute(difference)) throw new Error(`Source escaped its root: ${relative}`);
  return actual;
}

export async function inspectSource(rootInput) {
  const root = await fs.realpath(rootInput);
  const entries = [];
  const json = {};
  for (const file of IOS_SOURCE_FILES) {
    const actual = await approvedFile(root, file);
    const bytes = await fs.readFile(actual);
    const entry = { path: file, bytes: bytes.length, sha256: sha256(bytes) };
    if (file.startsWith('assets/')) entry.png = inspectPng(bytes, file);
    else {
      const text = bytes.toString('utf8');
      // Build scripts contain controlled malicious fixtures and detection patterns,
      // but are never part of Metro's runtime import graph.
      if (!buildScripts.has(file)) assertClientText(file, text);
      if (['app.json', 'eas.json', 'package.json'].includes(file)) json[file] = JSON.parse(text);
      if (file === 'package-lock.json') {
        const lock = JSON.parse(text);
        for (const pkg of Object.values(lock.packages ?? {})) {
          if (!pkg.resolved) continue;
          let url;
          try { url = new URL(pkg.resolved); } catch { throw new Error('Lockfile contains a local or invalid package reference.'); }
          if (url.protocol !== 'https:' || url.username || url.password) throw new Error('Lockfile package references must use HTTPS without credentials.');
        }
      }
      if (file === '.easignore' && text.replaceAll('\r\n', '\n') !== expectedEasIgnore()) throw new Error('.easignore has drifted from the reviewed source allowlist.');
    }
    entries.push(entry);
  }
  assertIosConfiguration(json['app.json'], json['eas.json'], json['package.json']);
  const defaults = await fs.readFile(path.join(root, 'src/types.ts'), 'utf8');
  if (!/export\s+const\s+emptyData\s*=\s*\([^)]*\)[^=]*=>\s*\(\{\s*version:\s*1,\s*profile:\s*\{\s*\},/.test(defaults)) {
    throw new Error('Fresh health records must begin with an empty profile. Review emptyData before packaging.');
  }
  const secureStore = await fs.readFile(path.join(root, 'src/ai-settings.ts'), 'utf8');
  if (!secureStore.includes('keychainAccessible: SecureStore.WHEN_UNLOCKED_THIS_DEVICE_ONLY')) throw new Error('The iOS AI credential store must remain unlocked-device-only and non-migrating.');
  return { entries, totalBytes: entries.reduce((total, entry) => total + entry.bytes, 0) };
}

export async function copySafeSource(rootInput, destinationInput) {
  const report = await inspectSource(rootInput);
  const root = await fs.realpath(rootInput);
  const destination = path.resolve(destinationInput);
  // Never overlay an existing checkout or an earlier preparation run.
  await fs.mkdir(path.dirname(destination), { recursive: true });
  await fs.mkdir(destination);
  for (const entry of report.entries) {
    const actual = await approvedFile(root, entry.path);
    const target = path.join(destination, ...entry.path.split('/'));
    await fs.mkdir(path.dirname(target), { recursive: true });
    await fs.copyFile(actual, target, constants.COPYFILE_EXCL);
    if (sha256(await fs.readFile(target)) !== entry.sha256) throw new Error(`Source changed during its snapshot: ${entry.path}`);
  }
  return report;
}

export async function listRegularFiles(rootInput) {
  const output = [];
  async function walk(current, relative = '') {
    for (const entry of await fs.readdir(current, { withFileTypes: true })) {
      const file = relative ? `${relative}/${entry.name}` : entry.name;
      const target = path.join(current, entry.name);
      const stat = await fs.lstat(target);
      if (stat.isSymbolicLink()) throw new Error(`Archive inputs must not contain links: ${file}`);
      if (stat.isDirectory()) await walk(target, file);
      else if (stat.isFile()) output.push(file);
      else throw new Error(`Archive inputs must be regular files: ${file}`);
    }
  }
  await walk(rootInput);
  return output.sort();
}

export async function createSourceArchive(sourceRoot, outputFile) {
  const report = await inspectSource(sourceRoot);
  const files = await listRegularFiles(sourceRoot);
  if (JSON.stringify(files) !== JSON.stringify(IOS_SOURCE_FILES)) throw new Error('The archive source directory contains unapproved files.');
  const { default: JSZip } = await import('jszip');
  const zip = new JSZip();
  for (const file of files) {
    zip.file(file, await fs.readFile(await approvedFile(await fs.realpath(sourceRoot), file)), {
      date: new Date('1980-01-01T00:00:00Z'),
      createFolders: false,
      unixPermissions: 0o100644,
    });
  }
  const bytes = await zip.generateAsync({ type: 'nodebuffer', compression: 'DEFLATE', platform: 'UNIX' });
  const reopened = await JSZip.loadAsync(bytes, { checkCRC32: true });
  const archivedPaths = Object.keys(reopened.files).sort();
  if (JSON.stringify(archivedPaths) !== JSON.stringify(files)) throw new Error('Archive member verification failed.');
  for (const entry of report.entries) {
    const member = reopened.files[entry.path];
    if (member.dir || (member.unixPermissions & 0o170000) !== 0o100000 || sha256(await member.async('nodebuffer')) !== entry.sha256) {
      throw new Error(`Archive bytes or file type did not match: ${entry.path}`);
    }
  }
  await fs.writeFile(outputFile, bytes, { flag: 'wx' });
  return { path: path.basename(outputFile), bytes: bytes.length, sha256: sha256(bytes), verifiedMembers: archivedPaths.length, entries: report.entries };
}

const invokedDirectly = process.argv[1] && await fs.realpath(process.argv[1]).catch(() => null) === fileURLToPath(import.meta.url);
if (invokedDirectly) {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
  const argument = process.argv[2];
  try {
    if (argument === '--write-easignore') {
      await fs.writeFile(path.join(root, '.easignore'), expectedEasIgnore(), 'utf8');
      console.log('Updated the exact EAS client source allowlist.');
    } else if (argument === '--stage' && process.argv[3]) {
      const result = await copySafeSource(root, process.argv[3]);
      console.log(JSON.stringify({ status: 'staged', reviewedFiles: result.entries.length, bytes: result.totalBytes }));
    } else if (argument === '--check') {
      if (process.env.EAS_BUILD === 'true' || process.env.EAS_BUILD === '1') {
        if (process.env.EXPO_NO_DOTENV !== '1' || process.env.EXPO_NO_CLIENT_ENV_VARS !== '1') throw new Error('EAS must disable dotenv and client environment injection.');
        if (Object.keys(process.env).some((name) => name.startsWith('EXPO_PUBLIC_'))) throw new Error('Remove client environment variables from this EAS project before building. Values are never logged.');
      }
      const result = await inspectSource(root);
      console.log(JSON.stringify({ status: 'passed', reviewedFiles: result.entries.length, bytes: result.totalBytes, dotenvAllowed: false, personalDataAllowed: false, linksAllowed: false }));
    } else {
      throw new Error('Usage: node scripts/ios-source-policy.mjs --check | --write-easignore | --stage NEW_DIRECTORY');
    }
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
