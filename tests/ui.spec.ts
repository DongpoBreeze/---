import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import { parseBackupArchive } from '../src/backup';

test('offline records and original photo survive restart, export and restore', async ({ page }, testInfo) => {
  const errors: string[] = [];
  page.on('pageerror', (error) => errors.push(error.message));
  page.on('dialog', (dialog) => { void dialog.accept(); });
  await page.goto('/', { waitUntil: 'domcontentloaded' });
  await expect(page.getByText('记饮食', { exact: true })).toBeVisible();
  await page.screenshot({ path: `artifacts/${testInfo.project.name}-today.png`, fullPage: true });
  await page.getByText('记饮食', { exact: true }).click();
  await page.getByLabel('食物名称', { exact: true }).fill('测试午餐');
  await page.getByLabel(/份量或参考物/).fill('一碗');
  const photo = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+a90sAAAAASUVORK5CYII=', 'base64');
  const photoPicker = page.waitForEvent('filechooser');
  await page.getByText('选择照片', { exact: true }).click();
  await (await photoPicker).setFiles({ name: 'original.png', mimeType: 'image/png', buffer: photo });
  await expect(page.getByText('餐前照片', { exact: true })).toBeVisible();
  await page.getByText('保存', { exact: true }).click();
  await expect(page.getByLabel('食物名称', { exact: true })).toHaveCount(0);
  await expect(page.getByText('记饮食', { exact: true })).toBeVisible();
  const video = Buffer.from(await page.evaluate(async () => {
    const canvas = document.createElement('canvas');
    canvas.width = 160; canvas.height = 90;
    const context = canvas.getContext('2d')!;
    const stream = canvas.captureStream(10);
    const recorder = new MediaRecorder(stream, { mimeType: 'video/webm' });
    const chunks: Blob[] = [];
    recorder.ondataavailable = (event) => chunks.push(event.data);
    const finished = new Promise<void>((resolve) => { recorder.onstop = () => resolve(); });
    recorder.start();
    let frame = 0;
    const draw = setInterval(() => {
      context.fillStyle = '#16745e'; context.fillRect(0, 0, 160, 90);
      context.fillStyle = '#ffffff'; context.fillRect((frame++ * 8) % 130, 20, 25, 50);
    }, 100);
    await new Promise((resolve) => setTimeout(resolve, 800));
    recorder.stop(); await finished; clearInterval(draw);
    stream.getTracks().forEach((track) => track.stop());
    return Array.from(new Uint8Array(await new Blob(chunks).arrayBuffer()));
  }));
  await page.getByText('记训练', { exact: true }).click();
  await page.getByText('有氧 / 其他', { exact: true }).click();
  await page.getByRole('textbox', { name: '运动类型', exact: true }).fill('快走测试');
  await page.getByLabel('时长（分钟）', { exact: true }).fill('20');
  const videoPicker = page.waitForEvent('filechooser');
  await page.getByText('添加', { exact: true }).click();
  await (await videoPicker).setFiles({ name: 'training.webm', mimeType: 'video/webm', buffer: video });
  await expect(page.locator('video')).toBeVisible();
  await expect.poll(() => page.locator('video').evaluate((element: HTMLVideoElement) => element.readyState)).toBeGreaterThanOrEqual(2);
  await page.locator('video').evaluate((element: HTMLVideoElement) => element.play());
  await expect.poll(() => page.locator('video').evaluate((element: HTMLVideoElement) => element.currentTime)).toBeGreaterThan(0);
  await page.getByText('保存', { exact: true }).click();
  await expect(page.getByRole('textbox', { name: '运动类型', exact: true })).toHaveCount(0);
  await page.getByText('记睡眠', { exact: true }).click();
  await page.getByLabel(/入睡（/).fill('2026-10-09 23:30');
  await page.getByLabel(/起床（/).fill('2026-10-10 07:00');
  await page.getByLabel(/清醒时长（/).fill('');
  await page.getByText('3 分', { exact: true }).click();
  await page.getByText('保存', { exact: true }).click();
  await expect(page.getByLabel(/入睡（/)).toHaveCount(0);
  await expect(page.getByText('记饮食', { exact: true })).toBeVisible();
  await page.reload();
  await page.getByRole('tab', { name: '我的', exact: true }).click();
  await page.getByRole('button', { name: '全部记录', exact: true }).click();
  await expect(page.getByText('测试午餐', { exact: true })).toBeVisible();
  await page.screenshot({ path: `artifacts/${testInfo.project.name}-records.png`, fullPage: true });
  await page.getByRole('tab', { name: '设置', exact: true }).click();
  const downloadEvent = page.waitForEvent('download');
  await page.getByText('导出完整备份', { exact: true }).click();
  const download = await downloadEvent;
  const zipPath = await download.path();
  expect(zipPath).toBeTruthy();
  const backup = await parseBackupArchive(new Uint8Array(await readFile(zipPath!)));
  expect(backup.data.meals).toHaveLength(1);
  expect(backup.data.trainings).toHaveLength(1);
  expect(backup.data.trainings[0].durationMinutes).toBe(20);
  expect(backup.data.sleeps).toHaveLength(1);
  expect(backup.data.sleeps[0].awakeMinutes).toBeNull();
  expect(backup.media).toHaveLength(2);
  expect(Buffer.from(backup.media.find((item) => item.kind === 'image')!.bytes)).toEqual(photo);
  expect(Buffer.from(backup.media.find((item) => item.kind === 'video')!.bytes)).toEqual(video);
  await page.getByText('删除本机数据', { exact: true }).click();
  await page.getByRole('tab', { name: '我的', exact: true }).click();
  await page.getByRole('button', { name: '全部记录', exact: true }).click();
  await expect(page.getByText('测试午餐', { exact: true })).toHaveCount(0);
  await page.getByRole('tab', { name: '设置', exact: true }).click();
  for (let i = 0; i < 2; i++) {
    const restored = page.waitForEvent('dialog', { predicate: (dialog) => dialog.message().includes('恢复完成') });
    const picker = page.waitForEvent('filechooser');
    await page.getByText('恢复备份', { exact: true }).click();
    await (await picker).setFiles({ name: 'backup.zip', mimeType: 'application/zip', buffer: await readFile(zipPath!) });
    await restored;
  }
  await page.getByRole('tab', { name: '我的', exact: true }).click();
  await page.getByRole('button', { name: '全部记录', exact: true }).click();
  await expect(page.getByText('测试午餐', { exact: true })).toHaveCount(1);
  await page.reload();
  await page.getByRole('tab', { name: '我的', exact: true }).click();
  await page.getByRole('button', { name: '全部记录', exact: true }).click();
  await expect(page.getByText('测试午餐', { exact: true })).toBeVisible();
  await page.getByText('快走测试', { exact: true }).click();
  await expect.poll(() => page.locator('video').evaluate((element: HTMLVideoElement) => element.readyState)).toBeGreaterThanOrEqual(2);
  await page.getByLabel('关闭', { exact: true }).click();
  await page.getByLabel('删除记录', { exact: true }).first().click();
  await expect(page.getByText('测试午餐', { exact: true })).toHaveCount(0);
  await page.getByRole('tab', { name: '设置', exact: true }).click();
  const afterDeleteDownload = page.waitForEvent('download');
  await page.getByText('导出完整备份', { exact: true }).click();
  const afterDelete = await afterDeleteDownload;
  const cleaned = await parseBackupArchive(new Uint8Array(await readFile((await afterDelete.path())!)));
  expect(cleaned.data.meals).toHaveLength(0);
  expect(cleaned.media.filter((item) => item.kind === 'image')).toHaveLength(0);
  expect(cleaned.data.summaries.every((item) => !item.markdown.includes('测试午餐'))).toBe(true);
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth);
  expect(overflow).toBe(false);
  expect(errors).toEqual([]);
});
